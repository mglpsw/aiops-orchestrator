#!/usr/bin/env python3
"""Deterministic materializer for the AgentReview v2 benchmark corpus (#88).

Reads authored `base/`/`mutated/` file pairs under
`evals/agent_review_v2/case_sources/<case_id>/` and derives, for each case:

- `reviewable_corpus/<case_id>/base/<relpath>`  -- byte-identical copy of the
  authored safe baseline; this is the only content ever materialized onto a
  functional path during OP-BENCH.
- `reviewable_corpus/<case_id>/mutation.patch`  -- a unified diff (base ->
  mutated) with real `a/<relpath>` / `b/<relpath>` headers, generated by
  `difflib.unified_diff` and round-trip verified with the real `patch(1)`
  binary (never assumed correct merely because it was generated from the
  same two inputs).
- `reviewable_corpus/<case_id>/expected.yaml` -- the case's meta.yaml fields
  plus a `patch_sha256` and, for defect-bearing cases, `line_start`/
  `line_end` DERIVED from the diff hunk (never hand-typed).
- `reviewable_corpus/<case_id>/applicability.yaml` -- the lane-applicability
  declaration derived from `family` in meta.yaml.

This script is pure and offline: no network, no provider call, no GitHub
write. It never applies `mutation.patch` to anything under `base/` in this
repository's own working tree -- `base/` in `reviewable_corpus/` is always
the SAFE content; the mutation is materialized only on a synthetic OP-BENCH
branch, never here.

Usage:
    python scripts/materialize-benchmark-case.py               # materialize all cases
    python scripts/materialize-benchmark-case.py --check        # verify byte-stability
    python scripts/materialize-benchmark-case.py --case-id <id> # materialize one case
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT_DIR = Path(__file__).resolve().parent.parent
SOURCES_DIR = ROOT_DIR / "evals" / "agent_review_v2" / "case_sources"
CORPUS_DIR = ROOT_DIR / "evals" / "agent_review_v2" / "reviewable_corpus"

VALID_FAMILIES = {
    "semantic_positive",
    "semantic_safe_counterexample",
}

LANE_APPLICABILITY_BY_FAMILY = {
    "semantic_positive": {
        "lane1_pipeline": "not_part_of_baseline",
        "aiops_subject_projection": "applicable",
        "codex_local_detection": "applicable",
        "codex_github_detection": "applicable",
        "human_detection": "applicable_or_deferred",
    },
    "semantic_safe_counterexample": {
        "lane1_pipeline": "not_part_of_baseline",
        "aiops_subject_projection": "applicable",
        "codex_local_detection": "applicable",
        "codex_github_detection": "applicable",
        "human_detection": "applicable_or_deferred",
    },
}


class MaterializeError(Exception):
    pass


_EXCLUDED_DIR_NAMES = {"__pycache__", ".git"}


def _discover_relpaths(base_dir: Path) -> list[str]:
    return sorted(
        str(p.relative_to(base_dir)).replace("\\", "/")
        for p in base_dir.rglob("*")
        if p.is_file() and not any(part in _EXCLUDED_DIR_NAMES for part in p.parts)
    )


def _unified_diff_text(relpath: str, base_text: str, mutated_text: str) -> str:
    diff_lines = list(
        difflib.unified_diff(
            base_text.splitlines(keepends=True),
            mutated_text.splitlines(keepends=True),
            fromfile=f"a/{relpath}",
            tofile=f"b/{relpath}",
        )
    )
    return "".join(diff_lines)


def _verify_patch_round_trip(relpath: str, base_text: str, mutated_text: str, patch_text: str) -> None:
    """Apply `patch_text` to `base_text` using the real `patch(1)` binary and
    confirm the result is byte-identical to `mutated_text`. Never trusts the
    diff merely because it was generated from these same two inputs."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        target = tmp_path / relpath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(base_text, encoding="utf-8")
        patch_file = tmp_path / "mutation.patch"
        patch_file.write_text(patch_text, encoding="utf-8")
        result = subprocess.run(
            ["patch", "-p1", "--batch", "-i", str(patch_file)],
            cwd=tmp_path,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            raise MaterializeError(
                f"patch round-trip failed for {relpath}: {result.stdout}\n{result.stderr}"
            )
        applied = target.read_text(encoding="utf-8")
        if applied != mutated_text:
            raise MaterializeError(
                f"patch round-trip produced different content than mutated/ for {relpath}"
            )


def _derive_defect_lines(patch_text: str) -> tuple[int, int] | None:
    """Derive (line_start, line_end) in the MUTATED file from the diff's own
    hunk header (`@@ -a,b +c,d @@`), covering the full added/changed range
    -- never hand-typed, always read back from the patch that was just
    round-trip verified."""
    added_starts: list[int] = []
    added_ends: list[int] = []
    for line in patch_text.splitlines():
        if line.startswith("@@"):
            # @@ -old_start,old_lines +new_start,new_lines @@
            parts = line.split("@@")[1].strip().split()
            new_part = next(p for p in parts if p.startswith("+"))
            new_part = new_part.lstrip("+")
            if "," in new_part:
                new_start_s, new_lines_s = new_part.split(",")
            else:
                new_start_s, new_lines_s = new_part, "1"
            new_start = int(new_start_s)
            new_lines = int(new_lines_s)
            if new_lines > 0:
                added_starts.append(new_start)
                added_ends.append(new_start + new_lines - 1)
    if not added_starts:
        return None
    return min(added_starts), max(added_ends)


def _load_meta(case_dir: Path) -> dict:
    meta_path = case_dir / "meta.yaml"
    if not meta_path.is_file():
        raise MaterializeError(f"missing meta.yaml under {case_dir}")
    meta = yaml.safe_load(meta_path.read_text(encoding="utf-8"))
    required = {"case_id", "target", "family", "expected_readiness", "safe_counterexample", "rationale"}
    missing = required - meta.keys()
    if missing:
        raise MaterializeError(f"{case_dir.name}: meta.yaml missing fields {sorted(missing)}")
    if meta["family"] not in VALID_FAMILIES:
        raise MaterializeError(
            f"{case_dir.name}: family {meta['family']!r} is not provider-reviewable "
            f"(must be one of {sorted(VALID_FAMILIES)}); this materializer only "
            "handles provider_review_applicable cases"
        )
    if meta["case_id"] != case_dir.name:
        raise MaterializeError(
            f"{case_dir.name}: meta.yaml case_id {meta['case_id']!r} does not match directory name"
        )
    is_positive = meta["family"] == "semantic_positive"
    if is_positive:
        required_positive = {"severity", "invariant", "root_cause", "file_path"}
        missing_positive = required_positive - meta.keys()
        if missing_positive:
            raise MaterializeError(
                f"{case_dir.name}: semantic_positive case missing {sorted(missing_positive)}"
            )
    return meta


def materialize_case(case_dir: Path) -> Path:
    case_id = case_dir.name
    meta = _load_meta(case_dir)

    base_dir = case_dir / "base"
    mutated_dir = case_dir / "mutated"
    if not base_dir.is_dir() or not mutated_dir.is_dir():
        raise MaterializeError(f"{case_id}: both base/ and mutated/ must exist")

    base_relpaths = _discover_relpaths(base_dir)
    mutated_relpaths = _discover_relpaths(mutated_dir)
    if base_relpaths != mutated_relpaths:
        raise MaterializeError(
            f"{case_id}: base/ and mutated/ must declare the identical file set "
            f"(base={base_relpaths}, mutated={mutated_relpaths})"
        )
    if not base_relpaths:
        raise MaterializeError(f"{case_id}: base/ is empty")

    patch_segments: list[str] = []
    all_line_ranges: list[tuple[str, int, int]] = []
    any_content_changed = False

    for relpath in base_relpaths:
        base_text = (base_dir / relpath).read_text(encoding="utf-8")
        mutated_text = (mutated_dir / relpath).read_text(encoding="utf-8")
        if base_text == mutated_text:
            continue
        any_content_changed = True
        diff_text = _unified_diff_text(relpath, base_text, mutated_text)
        _verify_patch_round_trip(relpath, base_text, mutated_text, diff_text)
        patch_segments.append(diff_text)
        derived = _derive_defect_lines(diff_text)
        if derived is not None:
            all_line_ranges.append((relpath, derived[0], derived[1]))

    if not any_content_changed:
        raise MaterializeError(f"{case_id}: mutated/ is byte-identical to base/ -- no change to review")

    mutation_patch_text = "".join(patch_segments)
    patch_sha256 = hashlib.sha256(mutation_patch_text.encode("utf-8")).hexdigest()

    out_dir = CORPUS_DIR / case_id
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_base_dir = out_dir / "base"
    for relpath in base_relpaths:
        dest = out_base_dir / relpath
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(base_dir / relpath, dest)

    (out_dir / "mutation.patch").write_text(mutation_patch_text, encoding="utf-8")

    is_positive = meta["family"] == "semantic_positive"
    expected: dict = {
        "case_id": case_id,
        "target": meta["target"],
        "family": meta["family"],
        "expected_readiness": meta["expected_readiness"],
        "safe_counterexample": meta["safe_counterexample"],
        "patch_sha256": patch_sha256,
        "changed_files": [relpath for relpath in base_relpaths if (base_dir / relpath).read_text(encoding="utf-8") != (mutated_dir / relpath).read_text(encoding="utf-8")],
        "rationale": meta["rationale"],
    }
    if is_positive:
        matching = [r for r in all_line_ranges if r[0] == meta["file_path"]]
        if not matching:
            raise MaterializeError(
                f"{case_id}: semantic_positive case declares file_path={meta['file_path']!r} "
                f"but the diff touched {[r[0] for r in all_line_ranges]}"
            )
        _, line_start, line_end = matching[0]
        expected.update(
            {
                "severity": meta["severity"],
                "file_path": meta["file_path"],
                "line_start": line_start,
                "line_end": line_end,
                "invariant": meta["invariant"],
                "root_cause": meta["root_cause"],
            }
        )
    (out_dir / "expected.yaml").write_text(
        yaml.safe_dump(expected, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )

    applicability = {
        "case_id": case_id,
        "family": meta["family"],
        "lane_applicability": LANE_APPLICABILITY_BY_FAMILY[meta["family"]],
        "reason": meta.get(
            "applicability_reason",
            "provider-reviewable synthetic defect/counterexample over real materialized code",
        ),
    }
    (out_dir / "applicability.yaml").write_text(
        yaml.safe_dump(applicability, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )

    return out_dir


def _diff_trees(a: Path, b: Path) -> list[str]:
    """Compare two directory trees for byte-stability. Excludes
    __pycache__/.git the same way materialize_case's own file discovery
    does -- local bytecode-cache noise from an unrelated tool invocation
    (e.g. compileall, or an ad hoc importlib run) in a REUSED worktree
    must never register as corpus drift."""
    a_files = {
        str(p.relative_to(a))
        for p in a.rglob("*")
        if p.is_file() and not any(part in _EXCLUDED_DIR_NAMES for part in p.parts)
    } if a.is_dir() else set()
    b_files = {
        str(p.relative_to(b))
        for p in b.rglob("*")
        if p.is_file() and not any(part in _EXCLUDED_DIR_NAMES for part in p.parts)
    } if b.is_dir() else set()
    problems = []
    for missing in sorted(a_files - b_files):
        problems.append(f"missing in regenerated output: {missing}")
    for extra in sorted(b_files - a_files):
        problems.append(f"unexpected in committed output: {extra}")
    for common in sorted(a_files & b_files):
        if (a / common).read_bytes() != (b / common).read_bytes():
            problems.append(f"content differs: {common}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case-id", help="materialize only this case (default: all under case_sources/)")
    parser.add_argument("--check", action="store_true", help="verify committed output is byte-stable")
    args = parser.parse_args()

    if not SOURCES_DIR.is_dir():
        print(f"no case_sources directory at {SOURCES_DIR}", file=sys.stderr)
        return 2

    case_dirs = sorted(p for p in SOURCES_DIR.iterdir() if p.is_dir())
    if args.case_id:
        case_dirs = [p for p in case_dirs if p.name == args.case_id]
        if not case_dirs:
            print(f"no case_source named {args.case_id!r}", file=sys.stderr)
            return 2

    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            tmp_corpus = Path(tmp) / "reviewable_corpus"
            global CORPUS_DIR  # noqa: PLW0603 -- intentional redirect for --check
            real_corpus_dir = CORPUS_DIR
            CORPUS_DIR = tmp_corpus
            try:
                errors = 0
                for case_dir in case_dirs:
                    try:
                        materialize_case(case_dir)
                    except MaterializeError as exc:
                        print(f"FAIL {case_dir.name}: {exc}", file=sys.stderr)
                        errors += 1
                if errors:
                    return 1
                all_problems: list[str] = []
                for case_dir in case_dirs:
                    problems = _diff_trees(real_corpus_dir / case_dir.name, tmp_corpus / case_dir.name)
                    all_problems.extend(f"{case_dir.name}: {p}" for p in problems)
                if all_problems:
                    for p in all_problems:
                        print(f"DRIFT {p}", file=sys.stderr)
                    return 1
                print(f"ok: reviewable_corpus/ is byte-identical to a fresh materialization ({len(case_dirs)} cases)")
                return 0
            finally:
                CORPUS_DIR = real_corpus_dir

    errors = 0
    for case_dir in case_dirs:
        try:
            out_dir = materialize_case(case_dir)
            print(f"materialized {case_dir.name} -> {out_dir.relative_to(ROOT_DIR)}")
        except MaterializeError as exc:
            print(f"FAIL {case_dir.name}: {exc}", file=sys.stderr)
            errors += 1
    if errors:
        return 1
    print(f"materialized {len(case_dirs)} case(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
